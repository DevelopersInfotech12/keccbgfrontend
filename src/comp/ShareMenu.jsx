/* Copy with fallback for non-secure contexts (http / older browsers). */
async function copyText(text, preview) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      if (preview) {
        const item = new ClipboardItem({
          "text/html": new Blob([preview], { type: "text/html" }),
          "text/plain": new Blob([text], { type: "text/plain" }),
        });
        await navigator.clipboard.write([item]);
      } else {
        await navigator.clipboard.writeText(text);
      }
      return true;
    }
  } catch {
    /* fall through to legacy path */
  }
  try {
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.setAttribute("readonly", "");
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(ta);
    return ok;
  } catch {
    return false;
  }
}

/* What each network app should show in the compose box. Preview cards are
   generated by each network from Open Graph tags on the linked page, so
   they need no text here. */
const compose = (target, url, text) => {
  switch (target) {
    case "whatsapp": return { url, text: `${text} ${url}` };
    case "x": return { url, text: `${text}\n${url}` };
    case "linkedin": return { url: `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(url)}`, text: text };
    case "facebook": return { url, text: text };
    case "copy": return { url, text: `${text}\n${url}` };
    default: return { url, text: "" };
  }
};

/* Shared preview card — the image + domain + title block that stands in
   for the Open Graph card each social app renders for the link. */
function SharePreviewCard({ item, url, variant = "compact" }) {
  const domain = url.replace(/^https?:\/\//, "").split("/")[0];
  const isCompact = variant === "compact";
  return (
    <div
      className={`overflow-hidden rounded-2xl border border-ink-900/10 bg-white ${isCompact ? "" : "shadow-sm"}`}
      role="img"
      aria-label={`Preview: ${item.title}`}
    >
      <img
        src={item.img}
        alt=""
        className={`w-full object-cover ${isCompact ? "h-40" : "aspect-[2.05/1]"}`}
        loading={isCompact ? undefined : "eager"}
        onError={(e) => { e.currentTarget.style.display = "none"; }}
      />
      <div className={`bg-white ${isCompact ? "p-3" : "px-4 py-3"}`}>
        <p className="truncate text-[11px] uppercase tracking-wide text-ink-300">{domain}</p>
        <p className={`mt-0.5 font-display font-semibold leading-snug text-ink-900 ${isCompact ? "line-clamp-2 text-[14.5px]" : "line-clamp-3 text-[13.5px]"}`}>
          {item.title}
        </p>
        <p className="mt-0.5 truncate text-[12px] text-ink-300">{item.category} · {item.date}</p>
      </div>
    </div>
  );
}

