const TARGET_LABELS = {
  whatsapp: "WhatsApp",
  x: "X",
  linkedin: "LinkedIn",
  facebook: "Facebook",
  email: "Email",
  copy: "Clipboard",
  native: "System share",
};

export default function ShareMenu({ item, onClose }) {
  const [copied, setCopied] = useState(false);
  const [mounted, setMounted] = useState(false);
  const [canNative, setCanNative] = useState(false);
  /* Which target's compose box is currently previewed (null = none). */
  const [previewTarget, setPreviewTarget] = useState(null);

  useEffect(() => {
    setMounted(true);
    setCanNative(typeof navigator !== "undefined" && typeof navigator.share === "function");
  }, []);

  /* Esc to close + lock body scroll while open. */
  useEffect(() => {
    if (!item) return undefined;
    const onKey = (e) => e.key === "Escape" && onClose();
    document.addEventListener("keydown", onKey);
    const prev = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.removeEventListener("keydown", onKey);
      document.body.style.overflow = prev;
    };
  }, [item, onClose]);

  useEffect(() => {
    setCopied(false);
    setPreviewTarget(null);
  }, [item]);

  if (!item || !mounted) return null;

  const url = getInfographicUrl(item.slug, window.location.origin);
  const text = getInfographicShareText(item);
  const eu = encodeURIComponent(url);
  const et = encodeURIComponent(text);

  const targets = [
    { key: "whatsapp", label: "WhatsApp", color: "#25D366", href: `https://wa.me/?text=${et}%20${eu}` },
    { key: "x", label: "X", color: "#0F1419", href: `https://twitter.com/intent/tweet?text=${et}&url=${eu}` },
    { key: "linkedin", label: "LinkedIn", color: "#0A66C2", href: `https://www.linkedin.com/sharing/share-offsite/?url=${eu}` },
    { key: "facebook", label: "Facebook", color: "#1877F2", href: `https://www.facebook.com/sharer/sharer.php?u=${eu}` },
  ];

  /* Rich clipboard (HTML preview card) for desktop / Safari; plain text elsewhere. */
  const richPreview = `
    <div style="max-width:380px;font-family:Helvetica,Arial,sans-serif;text-align:left;">
      <img src="${item.img}" style="width:100%;border-radius:8px;object-fit:cover;" alt="" />
      <div style="padding:10px 4px 0;">
        <div style="font-size:10px;letter-spacing:0.05em;text-transform:uppercase;color:#78909C;">${url.replace(/^https?:\/\//, "").split("/")[0]}</div>
        <div style="font-size:15px;font-weight:600;color:#111;margin-top:2px;">${item.title}</div>
        <div style="font-size:12px;color:#78909C;margin-top:2px;">${item.category} · ${item.date}</div>
      </div>
    </div>`;

  const handleCopy = async () => {
    const preview = canNative ? richPreview : null;
    const ok = await copyText(`${text}\n${url}`, preview);
    if (ok) {
      setPreviewTarget("copy");
      setCopied(true);
      setTimeout(() => setCopied(false), 2200);
    }
  };

  const handleNative = () => {
    setPreviewTarget("native");
    navigator.share({ title: item.title, text, url }).then(onClose).catch(() => {});
  };

  const preview = previewTarget ? compose(previewTarget, url, text) : null;

  return createPortal(
    <div
      role="dialog"
      aria-modal="true"
      aria-label={`Share ${item.title}`}
      className="fixed inset-0 z-[80] flex items-center justify-center bg-ink-900/70 p-4 backdrop-blur-sm"
      onClick={onClose}
    >
      <div
        className="relative max-h-[85vh] w-full max-w-md overflow-y-auto overflow-x-hidden rounded-3xl bg-white shadow-2xl"
        onClick={(e) => e.stopPropagation()}
      >
        <button
          type="button"
          onClick={onClose}
          aria-label="Close share dialog"
          className="absolute right-3 top-3 z-10 grid h-9 w-9 place-items-center rounded-full bg-white/90 text-ink-900 shadow"
        >
          <X className="h-4 w-4" aria-hidden="true" />
        </button>

        {/* Live preview of what the chosen target's compose box will hold */}
        <div className="border-b border-ink-900/8 bg-mist-50 p-4 pt-5">
          <p className="mb-2 text-[11px] font-bold uppercase tracking-[0.08em] text-ink-300">
            {preview ? `You’re sharing to ${TARGET_LABELS[previewTarget]}` : "Share preview"}
          </p>
          <SharePreviewCard item={item} url={url} variant={preview ? "social" : "compact"} />
          {preview && preview.text ? (
            <p className="mt-2 whitespace-pre-line px-1 text-[12px] leading-relaxed text-ink-300">{preview.text}</p>
          ) : null}
        </div>

        <div className="p-5">
          <p className="font-display text-[16px] font-semibold text-ink-900">Share this infographic</p>

          <div className="mt-4 grid grid-cols-5 gap-2">
            {targets.map((t) => (
              <a
                key={t.key}
                href={t.href}
                target="_blank"
                rel="noopener noreferrer"
                onClick={() => { setPreviewTarget(t.key); setTimeout(onClose, 150); }}
                className="group flex flex-col items-center gap-1.5 text-[11px] font-medium text-ink-800"
              >
                <span
                  className="grid h-11 w-11 place-items-center rounded-full text-white transition-transform group-hover:scale-110"
                  style={{ background: t.color }}
                >
                  {ICONS[t.key]}
                </span>
                {t.label}
              </a>
            ))}
            <a
              href={`mailto:?subject=${et}&body=${et}%0A${eu}`}
              onClick={() => { setPreviewTarget("email"); setTimeout(onClose, 150); }}
              className="group flex flex-col items-center gap-1.5 text-[11px] font-medium text-ink-800"
            >
              <span
                className="grid h-11 w-11 place-items-center rounded-full text-white transition-transform group-hover:scale-110"
                style={{ background: TEAL }}
              >
                <Mail className="h-5 w-5" aria-hidden="true" />
              </span>
              Email
            </a>
          </div>

          <div className="mt-5 flex items-center gap-2 rounded-full border border-ink-900/12 bg-mist-50 py-1.5 pl-4 pr-1.5">
            <Link2 className="h-4 w-4 shrink-0 text-ink-300" aria-hidden="true" />
            <input
              readOnly
              value={url}
              onFocus={(e) => e.target.select()}
              aria-label="Infographic link"
              className="min-w-0 flex-1 bg-transparent text-[12.5px] text-ink-800 outline-none"
            />
            <button
              type="button"
              onClick={handleCopy}
              className="inline-flex shrink-0 items-center gap-1.5 rounded-full px-4 py-2 text-[12.5px] font-semibold text-white transition-colors"
              style={{ background: copied ? "#16A34A" : ORANGE }}
            >
              {copied ? <Check className="h-3.5 w-3.5" aria-hidden="true" /> : <Copy className="h-3.5 w-3.5" aria-hidden="true" />}
              {copied ? "Copied" : "Copy"}
            </button>
          </div>
          <p aria-live="polite" className="sr-only">{copied ? "Link copied to clipboard" : ""}</p>

          {canNative && (
            <button
              type="button"
              onClick={handleNative}
              className="mt-3 inline-flex w-full items-center justify-center gap-2 rounded-full border border-ink-900/12 py-2.5 text-[13px] font-semibold text-ink-800 hover:border-leaf-500"
            >
              <Share2 className="h-4 w-4" aria-hidden="true" />
              More options…
            </button>
          )}
        </div>
      </div>
    </div>,
    document.body
  );
}
